-- SuaFacul — esquema inicial no PostgreSQL (Supabase)
--
-- Porta para PostgreSQL o esquema que vivia em database/init_db.py (SQLite),
-- com as mesmas tabelas, colunas, relacionamentos e regras de exclusão.
-- Idempotente: pode ser reaplicado (IF NOT EXISTS / CREATE OR REPLACE).
--
-- Aplicação: Supabase CLI (`supabase db push`), SQL Editor do painel, ou
-- automaticamente por `flask --app wsgi init-db` quando a conexão tem
-- permissão de DDL (ver database/init_db.py).
