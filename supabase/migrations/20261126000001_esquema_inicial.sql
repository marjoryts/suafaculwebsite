CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA extensions;
CREATE EXTENSION IF NOT EXISTS pg_trgm  WITH SCHEMA extensions;

-- Controle das migrations aplicadas (lido pelo init_db para saber o que falta).
CREATE TABLE IF NOT EXISTS public.suafacul_migracoes (
    versao      TEXT PRIMARY KEY,
    aplicada_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── Funções ─────────────────────────────────────────────────────────────

-- 'São Paulo' -> 'sao paulo'. Equivale a config.database.normalizar() no
-- Python (sem acentos + minúsculas). IMMUTABLE para poder ser indexada.
CREATE OR REPLACE FUNCTION public.normalizar(texto TEXT)
RETURNS TEXT
LANGUAGE sql IMMUTABLE PARALLEL SAFE
SET search_path = ''
AS $$ SELECT lower(extensions.unaccent('extensions.unaccent'::regdictionary, texto)) $$;

-- Data ISO 'AAAA-MM-DD' válida -> DATE; qualquer outra coisa -> NULL
-- (mesmo comportamento de date() do SQLite usado antes na ordenação).
CREATE OR REPLACE FUNCTION public.data_iso(texto TEXT)
RETURNS DATE
LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE
SET search_path = ''
AS $$
BEGIN
    IF texto IS NULL OR texto !~ '^\d{4}-\d{2}-\d{2}$' THEN
        RETURN NULL;
    END IF;
    RETURN texto::date;  -- '2026-02-30' levanta erro -> NULL (abaixo)
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END $$;

-- updated_at automático em qualquer UPDATE.
CREATE OR REPLACE FUNCTION public.definir_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$ BEGIN NEW.updated_at := now(); RETURN NEW; END $$;

-- ── Tabelas ─────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_usuario  TEXT NOT NULL UNIQUE,
    email         TEXT NOT NULL UNIQUE,
    senha         TEXT NOT NULL,              -- hash werkzeug (nunca a senha)
    tipo          TEXT NOT NULL DEFAULT 'aluno' CHECK (tipo IN ('aluno', 'admin')),
    google_id     TEXT,
    auth_provider TEXT NOT NULL DEFAULT 'local',
    avatar_url    TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_usuarios_google_id ON public.usuarios (google_id) WHERE google_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_usuarios_email_lower ON public.usuarios (lower(email));

CREATE TABLE IF NOT EXISTS public.faculdades (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_emec           TEXT UNIQUE,
    nome                  TEXT NOT NULL,
    sigla                 TEXT,
    organizacao_academica TEXT,
    tipo_instituicao      TEXT NOT NULL DEFAULT 'Pública' CHECK (tipo_instituicao IN ('Pública', 'Privada')),
    url                   TEXT,
    endereco              TEXT,
    cidade                TEXT,
    uf                    TEXT,
    telefone              TEXT,
    email                 TEXT,
    situacao              TEXT DEFAULT 'ativa',
    fonte                 TEXT DEFAULT 'manual',
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_faculdades_nome_trgm ON public.faculdades USING gin (public.normalizar(nome) extensions.gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_faculdades_sigla ON public.faculdades (sigla);
CREATE INDEX IF NOT EXISTS idx_faculdades_uf ON public.faculdades (upper(trim(uf)));
CREATE INDEX IF NOT EXISTS idx_faculdades_fonte ON public.faculdades (fonte);

CREATE TABLE IF NOT EXISTS public.cursos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              TEXT NOT NULL,
    instituicao       TEXT NOT NULL DEFAULT 'Instituição não informada',
    faculdade_id      BIGINT REFERENCES public.faculdades (id) ON DELETE SET NULL,
    modalidade        TEXT NOT NULL DEFAULT 'presencial',
    descricao         TEXT,
    duracao           TEXT,
    grau              TEXT,
    area              TEXT,
    tipo_instituicao  TEXT NOT NULL DEFAULT 'Pública',
    codigo_inep_curso TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_cursos_codigo_inep ON public.cursos (codigo_inep_curso) WHERE codigo_inep_curso IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_cursos_faculdade ON public.cursos (faculdade_id);
CREATE INDEX IF NOT EXISTS idx_cursos_nome_lower ON public.cursos (lower(nome) text_pattern_ops);  -- autocomplete por prefixo
CREATE INDEX IF NOT EXISTS idx_cursos_nome_trgm ON public.cursos USING gin (public.normalizar(nome) extensions.gin_trgm_ops);

CREATE TABLE IF NOT EXISTS public.vestibulares (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              TEXT NOT NULL,
    instituicao       TEXT,
    faculdade_id      BIGINT REFERENCES public.faculdades (id) ON DELETE SET NULL,
    tipo_instituicao  TEXT NOT NULL DEFAULT 'Pública',
    cidade            TEXT,
    regiao            TEXT,
    periodo_inscricao TEXT,
    -- Texto de propósito: o validador marca 'data_invalida' quando o valor não
    -- é uma data; ordenação e filtros usam public.data_iso(data_prova).
    data_prova        TEXT,
    descricao         TEXT,
    link_edital       TEXT,
    taxa_inscricao    TEXT,
    cursos_oferecidos TEXT,
    requisitos        TEXT,
    fonte             TEXT,
    seed_versao       INTEGER DEFAULT 0,
    status_validacao  TEXT DEFAULT 'nao_validado',
    cadastrado_ok     SMALLINT NOT NULL DEFAULT 0 CHECK (cadastrado_ok IN (0, 1)),
    ultima_validacao  TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_vestibulares_nome ON public.vestibulares (lower(nome));
CREATE INDEX IF NOT EXISTS idx_vestibulares_faculdade ON public.vestibulares (faculdade_id);
CREATE INDEX IF NOT EXISTS idx_vestibulares_data ON public.vestibulares (public.data_iso(data_prova));

-- item_id é polimórfico (curso/vestibular/faculdade conforme `tipo`), por isso
-- sem FK: a existência do item é validada em favorito_service.
CREATE TABLE IF NOT EXISTS public.favoritos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
    tipo       TEXT NOT NULL CHECK (tipo IN ('curso', 'vestibular', 'faculdade')),
    item_id    BIGINT NOT NULL,
    nome_item  TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (usuario_id, tipo, item_id)
);
CREATE INDEX IF NOT EXISTS idx_favoritos_item ON public.favoritos (tipo, item_id);

-- usuario_id NULL = teste anônimo, ou de usuário excluído (SET NULL preserva a
-- estatística sem dado pessoal). Ver docs/banco-de-dados.md.
CREATE TABLE IF NOT EXISTS public.teste_vocacional_resultados (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT REFERENCES public.usuarios (id) ON DELETE SET NULL,
    perfil_principal TEXT NOT NULL,
    perfis_json      TEXT NOT NULL,
    respostas_json   TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_teste_vocacional_usuario ON public.teste_vocacional_resultados (usuario_id);

CREATE TABLE IF NOT EXISTS public.automacao_logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo          TEXT NOT NULL,
    executado_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
    sucesso       SMALLINT NOT NULL DEFAULT 1 CHECK (sucesso IN (0, 1)),
    resumo        TEXT,
    erro          TEXT,
    execucao_id   TEXT,
    status        TEXT CHECK (status IN ('executando', 'sucesso', 'falha', 'ignorada')),
    origem        TEXT,
    iniciado_em   TIMESTAMPTZ,
    finalizado_em TIMESTAMPTZ,
    duracao_ms    INTEGER
);
-- Trava: no máximo UMA execução 'executando' por tipo.
CREATE UNIQUE INDEX IF NOT EXISTS idx_automacao_em_execucao ON public.automacao_logs (tipo) WHERE status = 'executando';
CREATE INDEX IF NOT EXISTS idx_automacao_tipo_status ON public.automacao_logs (tipo, status, finalizado_em);
CREATE INDEX IF NOT EXISTS idx_automacao_execucao_id ON public.automacao_logs (execucao_id);

-- Sessões do app Mobile. Só o hash SHA-256 do refresh token é guardado.
CREATE TABLE IF NOT EXISTS public.refresh_tokens (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    familia_id       TEXT NOT NULL,
    usuario_id       BIGINT NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
    token_hash       TEXT NOT NULL UNIQUE,
    dispositivo      TEXT,
    expira_em        TIMESTAMPTZ NOT NULL,
    usado_em         TIMESTAMPTZ,
    revogado_em      TIMESTAMPTZ,
    motivo_revogacao TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_familia ON public.refresh_tokens (familia_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_usuario ON public.refresh_tokens (usuario_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expira ON public.refresh_tokens (expira_em);

-- Catálogo de formações da home (uma linha por formação).
CREATE TABLE IF NOT EXISTS public.cursos_catalogo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        TEXT NOT NULL,
    area        TEXT,
    grau        TEXT,
    duracao     TEXT,
    descricao   TEXT,
    imagem_url  TEXT,
    ordem       INTEGER DEFAULT 0,
    seed_versao INTEGER DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Equivale ao UNIQUE ... COLLATE NOCASE do SQLite.
CREATE UNIQUE INDEX IF NOT EXISTS idx_cursos_catalogo_nome ON public.cursos_catalogo (lower(nome));

-- ── Gatilhos de updated_at ──────────────────────────────────────────────
DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['usuarios', 'faculdades', 'cursos', 'vestibulares', 'cursos_catalogo'] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated_at ON public.%1$I', t);
        EXECUTE format('CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON public.%1$I '
                       'FOR EACH ROW EXECUTE FUNCTION public.definir_updated_at()', t);
    END LOOP;
END $$;

